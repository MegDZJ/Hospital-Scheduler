#!/usr/bin/env python3
"""Build-time helper: turns the files in web/ into a C header.

Usage: embed_assets.py <web_dir> <output_header>

This script is only used while building.  The running application is pure C
and serves the bytes embedded in the generated header.
"""
import os
import sys

ASSETS = [
    ("/",           "index.html", "text/html; charset=utf-8"),
    ("/index.html", "index.html", "text/html; charset=utf-8"),
    ("/styles.css", "styles.css", "text/css; charset=utf-8"),
    ("/app.js",     "app.js",     "application/javascript; charset=utf-8"),
]


def main():
    if len(sys.argv) != 3:
        print(__doc__)
        return 2
    web_dir, out_path = sys.argv[1], sys.argv[2]

    blobs = {}
    for _, filename, _ in ASSETS:
        if filename not in blobs:
            with open(os.path.join(web_dir, filename), "rb") as f:
                blobs[filename] = f.read()

    lines = [
        "/* GENERATED by scripts/embed_assets.py - do not edit. */",
        "#ifndef EMBEDDED_ASSETS_H",
        "#define EMBEDDED_ASSETS_H",
        "",
        "#include <stddef.h>",
        "#include <string.h>",
        "",
        "typedef struct {",
        "    const char          *path;",
        "    const char          *content_type;",
        "    const unsigned char *data;",
        "    size_t               size;",
        "} EmbeddedAsset;",
        "",
    ]

    names = {}
    for i, (filename, data) in enumerate(blobs.items()):
        var = "asset_data_%d" % i
        names[filename] = (var, len(data))
        lines.append("static const unsigned char %s[] = {" % var)
        for off in range(0, len(data), 16):
            chunk = data[off:off + 16]
            lines.append("    " + ",".join("0x%02x" % b for b in chunk) + ",")
        lines.append("    0x00")  # keeps the array non-empty
        lines.append("};")
        lines.append("")

    lines.append("static const EmbeddedAsset embedded_assets[] = {")
    for path, filename, ctype in ASSETS:
        var, size = names[filename]
        lines.append('    { "%s", "%s", %s, %d },' % (path, ctype, var, size))
    lines.append("};")
    lines.append("")
    lines.append("static const EmbeddedAsset *find_embedded_asset(const char *path)")
    lines.append("{")
    lines.append("    size_t i;")
    lines.append("    for (i = 0; i < sizeof(embedded_assets) / sizeof(embedded_assets[0]); i++) {")
    lines.append("        if (strcmp(embedded_assets[i].path, path) == 0)")
    lines.append("            return &embedded_assets[i];")
    lines.append("    }")
    lines.append("    return NULL;")
    lines.append("}")
    lines.append("")
    lines.append("#endif")
    lines.append("")

    os.makedirs(os.path.dirname(os.path.abspath(out_path)), exist_ok=True)
    with open(out_path, "w", newline="\n") as f:
        f.write("\n".join(lines))
    print("embedded %d files -> %s" % (len(blobs), out_path))
    return 0


if __name__ == "__main__":
    sys.exit(main())
